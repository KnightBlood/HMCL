using System;
using System.IO;
using System.IO.Compression;

namespace HMCLCore.NET.Util;

/// <summary>
/// Utilities for detecting the compatibility of the zlib implementation of the
/// runtime.
/// </summary>
/// <remarks>
/// Some systems replace the zlib of the runtime with an alternative such as
/// zlib-ng, which may produce compressed output that differs byte-for-byte
/// from the output of the standard zlib. This can cause hash mismatches when
/// verifying artifacts whose expected checksums were computed with a specific
/// zlib implementation.
/// </remarks>
public static class ZlibUtils
{
    /// <summary>
    /// The compressed form of five zero bytes, as produced by the zlib
    /// implementation bundled with the runtime.
    /// </summary>
    private static readonly byte[] ExpectedCompressed =
    {
        0x78, 0x9C, 0x63, 0x60, 0x60, 0x60, 0x60, 0x00, 0x00, 0x00, 0x05, 0x00, 0x01
    };

    /// <summary>
    /// Whether the zlib implementation of the runtime produces output that is
    /// byte-for-byte identical to the expected output for a known test vector.
    /// </summary>
    /// <remarks>
    /// When this flag is <c>false</c>, the hash verification of the files that
    /// are generated by the launcher itself, such as the JAR files built by the
    /// installers of the mod loaders, has to be relaxed to a structural check,
    /// because the alternative zlib may legitimately produce files with
    /// different checksums.
    /// </remarks>
    public static bool IsZlibCompatible { get; } = CheckCompatibility();

    /// <summary>
    /// Compresses the given data with the zlib format of the runtime.
    /// </summary>
    /// <param name="data">The data to compress.</param>
    /// <returns>The compressed data.</returns>
    public static byte[] Compress(byte[] data)
    {
        using var output = new MemoryStream();

        using (var zlib = new ZLibStream(output, CompressionLevel.Optimal, true))
            zlib.Write(data, 0, data.Length);

        return output.ToArray();
    }

    /// <summary>
    /// Decompresses the given data with the zlib format.
    /// </summary>
    /// <param name="data">The data to decompress.</param>
    /// <returns>The decompressed data.</returns>
    public static byte[] Decompress(byte[] data)
    {
        using var input = new MemoryStream(data);
        using var zlib = new ZLibStream(input, CompressionMode.Decompress);
        using var output = new MemoryStream();

        zlib.CopyTo(output);
        return output.ToArray();
    }

    /// <summary>
    /// Compresses the five zero bytes of the test vector and compares the
    /// result with the expected output.
    /// </summary>
    /// <returns>Whether the zlib of the runtime behaves like the standard one.</returns>
    private static bool CheckCompatibility()
    {
        try
        {
            var compressed = Compress(new byte[5]);
            if (compressed.Length != ExpectedCompressed.Length)
                return false;

            for (var i = 0; i < compressed.Length; i++)
            {
                if (compressed[i] != ExpectedCompressed[i])
                    return false;
            }

            return true;
        }
        catch (Exception)
        {
            // The runtime cannot compress the test vector; the compatibility
            // cannot be guaranteed.
            return false;
        }
    }
}
